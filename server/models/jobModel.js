const mongoose=require('mongoose');

const jobSchema=new mongoose.Schema({
    title:{
        type:String,
        required:true
    },
    description:{
        type:String,
        required:true
    },
    jobType:{
        type:String,
        enum:['full-time','part-time','internship','contract','freelance'],
        default:'full-time',
    },
    workplace:{
        type:String,
        enum:['onsite','remote','hybrid'],
        default:'onsite'
    },
    status:{
        type:String,
        enum:['active','closed','draft'],
        default:'active'
    },
    paymentStatus:{
        type:String,
        enum:['not_required','unpaid','paid'],
        default:'not_required'
    },
    isFeatured:{
        type:Boolean,
        default:false
    },
    paidAt:{
        type:Date
    },
    location:{
        type:String,
        required:true
    },
    salary:{
        type:Number
    },
    featuredUntil:{
        type:Date
    },
    views:{
        type:Number,
        default:0
    },
    clicks:{
        type:Number,
        default:0
    },
    applicationCount:{
        type:Number,
        default:0
    },
    createdBy:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'UserModel',
        required:true
    },
    applications: [
        {
            user: {
                type: mongoose.Schema.Types.ObjectId,
                ref: 'UserModel'
            },
            appliedAt: {
                type: Date,
                default: Date.now
            },
            status:{
                type:String,
                enum:['pending','shortlisted','rejected','hired'],
                default:'pending'
            },
            note:{
                type:String,
                default:''
            },
            resumeUrl:{
                type:String,
                default:''
            },
            resumeText:{
                type:String,
                default:''
            },
            bid:{
                amount:{
                    type:Number
                },
                currency:{
                    type:String,
                    default:'USD'
                },
                type:{
                    type:String,
                    enum:['fixed','hourly','monthly'],
                    default:'fixed'
                },
                estimatedDuration:{
                    type:String,
                    default:''
                },
                availability:{
                    type:String,
                    default:''
                }
            },
            ats:{
                score:{
                    type:Number,
                    default:0
                },
                matchedKeywords:[String],
                missingKeywords:[String],
                summary:{
                    type:String,
                    default:''
                }
            },
            candidateSnapshot:{
                name:String,
                email:String,
                bio:String,
                skills:[String],
                education:String,
                experience:String,
                resumeUrl:String,
                expectedRate:Number,
                availability:String
            },
            stage:{
                type:String,
                enum:['applied','screening','interviewing','offered','hired','rejected'],
                default:'applied'
            },
            interviews:[
                {
                    scheduledAt:{type:Date},
                    duration:{type:Number,default:30},
                    type:{type:String,enum:['technical','hr','behavioral','other'],default:'technical'},
                    status:{type:String,enum:['scheduled','completed','cancelled'],default:'scheduled'},
                    feedback:{type:String,default:''},
                    interviewer:{type:String,default:''}
                }
            ],
            notes:[
                {
                    note:{type:String,required:true},
                    addedBy:{type:mongoose.Schema.Types.ObjectId,ref:'UserModel'},
                    addedByName:{type:String},
                    createdAt:{type:Date,default:Date.now}
                }
            ],
            stageHistory:[
                {
                    stage:{type:String},
                    updatedBy:{type:mongoose.Schema.Types.ObjectId,ref:'UserModel'},
                    updatedByName:{type:String},
                    updatedAt:{type:Date,default:Date.now}
                }
            ]
        }
    ]
},{timestamps:true});


module.exports=mongoose.model('jobModel',jobSchema);
